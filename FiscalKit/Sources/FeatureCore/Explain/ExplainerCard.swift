import FiscalDesignSystem
import SwiftUI

extension EnvironmentValues {
    @Entry public var explainer: Explainer = .shared
}

public struct ExplainerCard: View {
    public enum Style: Sendable {
        case card, caption
    }

    private struct Shown: Equatable {
        let id: String
        let output: ExplainerOutput
    }

    @Environment(\.explainer) private var explainer
    @Environment(\.accessibilityReduceMotion) private var reduceMotion
    @Environment(\.redactionReasons) private var redactionReasons
    @State private var shown: Shown?
    private let explanation: Explanation
    private let style: Style
    private let streaming: Bool

    public init(_ explanation: Explanation, style: Style = .card, streaming: Bool = false) {
        self.explanation = explanation
        self.style = style
        self.streaming = streaming
    }

    private var output: ExplainerOutput {
        guard let shown, shown.id == explanation.id else {
            return ExplainerOutput(text: explanation.fixed, origin: .fixed, isFinal: false)
        }
        return shown.output
    }

    public var body: some View {
        content
            .accessibilityElement(children: .combine)
            .task(id: explanation.id) {
                guard !redactionReasons.contains(.placeholder) else { return }
                for await next in explainer.explain(explanation, streaming: streaming) {
                    withAnimation(reduceMotion ? nil : .smooth) {
                        shown = Shown(id: explanation.id, output: next)
                    }
                }
            }
    }

    @ViewBuilder private var content: some View {
        let output = output
        switch style {
        case .card:
            VStack(alignment: .leading, spacing: .spaceS) {
                Label("What This Means", systemImage: "text.bubble")
                    .font(.caption.weight(.semibold))
                    .foregroundStyle(.secondary)
                    .textCase(.uppercase)
                Text(verbatim: output.text)
                    .font(.callout)
                    .fixedSize(horizontal: false, vertical: true)
                    .contentTransition(.opacity)
                if output.origin == .model {
                    ExplainerBadge()
                        .transition(.opacity)
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
            .padding(.vertical, .space2XS)
        case .caption:
            VStack(alignment: .leading, spacing: .spaceXS) {
                Text(verbatim: output.text)
                    .font(.footnote)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
                    .contentTransition(.opacity)
                if output.origin == .model {
                    ExplainerBadge()
                        .transition(.opacity)
                }
            }
            .frame(maxWidth: .infinity, alignment: .leading)
        }
    }
}

public struct ExplainerBadge: View {
    public init() {}

    public var body: some View {
        HStack(spacing: .space2XS) {
            Image(systemName: "apple.intelligence")
                .symbolRenderingMode(.multicolor)
                .accessibilityHidden(true)
            Text(Self.text)
                .fixedSize(horizontal: false, vertical: true)
        }
        .font(.caption2.weight(.semibold))
        .foregroundStyle(.secondary)
        .padding(.horizontal, .spaceS)
        .padding(.vertical, .space2XS)
        .background(Color.secondary.opacity(.opacityFill), in: .rect(cornerRadius: .radiusS))
    }

    private static var text: LocalizedStringKey {
        #if os(macOS)
            "Explanation generated by Apple Intelligence on your Mac · it can be wrong; the official text is the source"
        #elseif os(visionOS)
            "Explanation generated by Apple Intelligence on your Apple Vision Pro · it can be wrong; the official text is the source"
        #else
            UIDevice.current.userInterfaceIdiom == .pad
                ? "Explanation generated by Apple Intelligence on your iPad · it can be wrong; the official text is the source"
                : "Explanation generated by Apple Intelligence on your iPhone · it can be wrong; the official text is the source"
        #endif
    }
}
