const url = (bytes) => Buffer.from(bytes).toString('base64url');
const base64 = (bytes) => Buffer.from(bytes).toString('base64');

export function buildVector({ info = INFO, link = LINK, snapshot = SAMPLE } = {}) {
  const web = createECDH('prime256v1');
  web.setPrivateKey(Buffer.from(WEB_PRIVATE_KEY, 'hex'));
  const app = createECDH('prime256v1');
  app.setPrivateKey(Buffer.from(APP_PRIVATE_KEY, 'hex'));
  const session = Buffer.from(SESSION, 'hex');
  const sessionID = url(session);
  const secret = app.computeSecret(web.getPublicKey());
  const key = Buffer.from(hkdfSync('sha256', secret, session, Buffer.from(info), 32));
  const plaintext = JSON.stringify(snapshot);
  const nonce = Buffer.from(NONCE, 'hex');
  const cipher = createCipheriv('aes-256-gcm', key, nonce);
  cipher.setAAD(Buffer.from(sessionID, 'utf8'));
  const ciphertext = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final(), cipher.getAuthTag()]);
  return {
    description: `Shared web companion v2 test vector (docs/web.md). ECDH P-256 shared secret (x coordinate, 32 bytes) -> HKDF-SHA256(salt = raw session bytes, info = "${info}", 32 bytes) -> AES-256-GCM, AAD = UTF-8 of the base64url session id, ciphertext = ct || tag. Public keys are raw uncompressed (65 bytes). Generated by scripts/web-vector.mjs.`,
    webPrivateKeyHex: WEB_PRIVATE_KEY,
    webPublicKey: url(web.getPublicKey()),
    appPrivateKeyHex: APP_PRIVATE_KEY,
    appPublicKey: url(app.getPublicKey()),
    sessionHex: SESSION,
    sessionID,
    link: `${link}?s=${sessionID}&k=${url(web.getPublicKey())}`,
    sharedSecretHex: secret.toString('hex'),
    keyHex: key.toString('hex'),
    package: { v: 2, appKey: base64(app.getPublicKey()), nonce: base64(nonce), ciphertext: base64(ciphertext) },
    plaintext,
    snapshot
  };
}

